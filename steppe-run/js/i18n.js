let lang = 'uk';

// Device language → supported language; ru/be devices (common in Ukraine) default to Ukrainian.
const LANG_ALIASES = { ru: 'uk', be: 'uk' };
export function detectLang() {
  const nav = (navigator.language || 'uk').toLowerCase().slice(0, 2);
  const id = LANG_ALIASES[nav] || nav;
  return S[id] ? id : 'en';
}

export function setLang(id) { lang = S[id] ? id : 'en'; document.documentElement.lang = lang; }
export function getLang() { return lang; }

function fill(str, vars) {
  return str.replace(/\{(\w+)\}/g, (m, k) => (vars && k in vars ? vars[k] : k === 'eb' || k === 'ebFull' ? t(k) : m));
}

export function t(key, vars) {
  const s = S[lang][key] ?? S.en[key] ?? S.uk[key] ?? key;
  return fill(s, vars);
}

export function shoutLines(cat) { return (S[lang].sh && S[lang].sh[cat]) || S.en.sh[cat]; }
export function actLine(key) { return (S[lang].act && S[lang].act[key]) || S.en.act[key]; }

// Static DOM text: data-i18n → textContent, data-i18n-html → innerHTML.
export function applyDom(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
}
